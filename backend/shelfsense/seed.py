@dataclass
class DayRecord:
    day: date
    units: int
    in_stock: bool


# SKUs deliberately left thin so the demo has real reorder pressure; everything else gets ~2-3 weeks of cover.
LOW_STOCK = {"G-RICE-BAS-5", "G-OIL-SUN-1", "P-SUN-50", "E-PBANK-10", "G-OATS-1", "G-MILK-1"}


def build_products(seed: int = 3) -> list[Product]:
    rng = random.Random(seed)
    out = []
    for sku, name, cat, brand, price, cost, stock, lead, pack, tags, aliases, attrs, base in _P:
        if sku not in LOW_STOCK:
            stock = max(4, round(base * rng.uniform(14, 24)))
        out.append(
            Product(
                sku=sku,
                name=name,
                category=cat,
                brand=brand,
                price=float(price),
                cost=float(cost),
                stock=stock,
                lead_time_days=lead,
                pack_size=pack,
                tags=tags,
                aliases=aliases,
                attributes=attrs,
            )
        )
    return out


