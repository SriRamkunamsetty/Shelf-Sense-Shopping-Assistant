def build_sales(today: date | None = None, seed: int = 7) -> dict[str, list[DayRecord]]:
    """Daily unit sales per SKU with weekly seasonality, trend, noise and stock-outs.

    Days on which a SKU was out of stock record ``in_stock=False`` and (near-)zero sales — i.e. the
    classic *censored demand* problem that naive forecasters get wrong.
    """
    today = today or datetime.now(UTC).date()
    rng = random.Random(seed)
    sales: dict[str, list[DayRecord]] = {}
    start = today - timedelta(days=HISTORY_DAYS)
    for p in _P:
        sku, cat, stock, base = p[0], p[2], p[6], p[12]
        trend = rng.uniform(-0.0008, 0.0025)
        weekend_boost = {
            "Grocery": 0.22,
            "Personal Care": 0.1,
            "Home": 0.12,
            "Electronics": 0.2,
            "Apparel": 0.3,
            "Stationery": -0.1,
        }[cat]
        phase = rng.uniform(0, 0.6)
        # a couple of historical stock-out windows + (for SKUs currently at zero) an ongoing one
        outages: set[int] = set()
        for _ in range(2 if base >= 2 else 1):
            s = rng.randint(10, HISTORY_DAYS - 25)
            outages.update(range(s, s + rng.randint(2, 4)))
        if stock == 0:
            outages.update(range(HISTORY_DAYS - 5, HISTORY_DAYS))
        rows = []
        for i in range(HISTORY_DAYS):
            d = start + timedelta(days=i)
            dow = d.weekday()
            season = (
                1 + weekend_boost * (1 if dow >= 5 else 0) + 0.08 * math.sin(2 * math.pi * (dow / 7 + phase))
            )
            mean = max(0.0, base * season * (1 + trend * i))
            demand = max(0, round(rng.gauss(mean, math.sqrt(mean) * 0.85 + 0.2)))
            if i in outages:
                rows.append(DayRecord(d, 0, False))
            else:
                rows.append(DayRecord(d, demand, True))
        sales[sku] = rows
    return sales
